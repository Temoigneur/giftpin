#!/usr/bin/env python3
"""Work out how wide to show each guide image so Shopify's left menu looks the same size everywhere.

  python3 scripts/measure-menu-widths.py

For every image that starts with a dark left-menu panel, finds that panel's width in pixels and writes
app/marketing/guide-copy/menu-sizes.ts: the image's display width = native width * MENU_PX / panel width.
"""
import os
from PIL import Image

MENU_PX = 180  # how wide the menu itself should look on the page
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAMES = [
    "p3-nav-settings", "p4-nav-promotions", "p5-nav-discounts", "p6-nav-analytics", "p7-nav-registries", "p8-nav-instore",
    "p9-pos-menu", "p9-products", "p9-settings", "p9-settings-channels", "p11-click-giftpin", "p12-nav-plan",
    "p21-nav-apps", "p21-nav-giftpin", "p21-nav-overview-click",
    "p11-open-apps", "p14-gift-card-path", "p14-import-path", "p14-order-processing-path", "p16-order-panel-path",
    "p16-customer-panel-path", "p17-flow-path", "p18-theme-block-path", "p20-menu-item-path",
]

def panel_width(path):
    im = Image.open(path).convert("L")
    w, h = im.size
    px = im.load()
    y0, y1 = int(h * 0.08), int(min(h, 400) * 0.55)
    ys = range(y0, max(y0 + 1, y1), 2)
    for x in range(40, w):
        dark = sum(1 for y in ys if px[x, y] < 60) / len(ys)
        if dark < 0.3:
            return x
    return w

out = {}
for sub, prefix in (("", "/guides/"), ("es/", "/guides/es/"), ("fr/", "/guides/fr/"), ("hi/", "/guides/hi/")):
    for n in NAMES:
        p = f"{root}/public/guides/{sub}{n}.png"
        if not os.path.exists(p):
            continue
        W = Image.open(p).width
        pw = panel_width(p)
        out[prefix + n + ".png"] = (round(W * MENU_PX / pw), W, pw)

lines = ["// Generated by scripts/measure-menu-widths.py: display width (px) per image so the left menu is the same size everywhere.",
         "export const MENU_SIZE: Record<string, number> = {"]
for k, (d, W, pw) in sorted(out.items()):
    lines.append(f'  "{k}": {d}, // native {W}, menu {pw}')
lines.append("};")
open(f"{root}/app/marketing/guide-copy/menu-sizes.ts", "w").write("\n".join(lines) + "\n")
print("\n".join(lines))
