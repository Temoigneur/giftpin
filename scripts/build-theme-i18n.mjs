// Builds extensions/registry-button/assets/giftpin-i18n.js from locales/*.json.
// Run: node scripts/build-theme-i18n.mjs   (tested by scripts/__tests__/theme-i18n.test.ts)
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "extensions", "registry-button");

export function buildThemeI18n() {
  const dict = {};
  for (const f of readdirSync(join(root, "locales")).sort()) {
    if (f === "en.default.json" || !f.endsWith(".json")) continue;
    const flat = {};
    const data = JSON.parse(readFileSync(join(root, "locales", f), "utf8"));
    for (const [section, keys] of Object.entries(data)) {
      for (const [k, v] of Object.entries(keys)) flat[`${section}.${k}`] = v;
    }
    dict[f.replace(/\.json$/, "")] = flat;
  }
  return `// GENERATED by scripts/build-theme-i18n.mjs from locales/*.json. Do not edit.
//
// Theme blocks are translated by Shopify's \`t\` filter, which only follows the
// storefront's own language. A store that sets its language in Giftpin
// (Settings -> Language) but keeps an English-only storefront would still see
// English, so blocks also carry data-gp-lang (the Giftpin language, set only
// when the storefront itself is English) and this file swaps the text in.
(function () {
  var DICT = ${JSON.stringify(dict)};
  var ATTRS = {
    "data-label-adding": "add_to_registry.adding",
    "data-label-added": "add_to_registry.added",
    "data-label-added-short": "add_to_registry.added_short",
    "data-label-error": "add_to_registry.error",
    "data-label-back": "add_to_registry.back",
    "data-label-updating": "add_to_registry.updating",
    "data-label-updated": "add_to_registry.updated",
    "data-label-update-error": "add_to_registry.update_error",
    "data-label-dup-message": "add_to_registry.dup_message",
    "data-label-dup-short": "add_to_registry.dup_short",
    "data-label-copy-prompt": "add_to_registry.copy_prompt",
    "data-label-babylist-error": "add_to_registry.babylist_error",
    "data-label-link-copied": "add_to_registry.link_copied"
  };
  var SAVE_ATTRS = {
    "data-label-save": "save_for_later.label",
    "data-label-saved": "save_for_later.saved",
    "data-label-error": "save_for_later.error",
    "data-label-add": "save_for_later.add_to_registry",
    "data-label-remove": "save_for_later.remove"
  };

  function get(lang, key, vars) {
    var d = DICT[lang];
    if (!d || typeof d[key] !== "string") return null;
    var s = d[key].replace(/\\{\\{\\s*qty\\s*\\}\\}/g, "__QTY__");
    if (vars) for (var k in vars) s = s.replace(new RegExp("\\\\{\\\\{\\\\s*" + k + "\\\\s*\\\\}\\\\}", "g"), vars[k]);
    return s;
  }

  function apply(root) {
    var lang = root && root.getAttribute && root.getAttribute("data-gp-lang");
    if (!lang || !DICT[lang] || root.getAttribute("data-gp-done")) return;
    root.setAttribute("data-gp-done", "1");
    var vars = { shop: root.getAttribute("data-shop-name") || "" };
    var map = root.hasAttribute("data-giftpin-save-root") || root.hasAttribute("data-giftpin-saved-root") ? SAVE_ATTRS : ATTRS;
    Object.keys(map).forEach(function (attr) {
      if (!root.hasAttribute(attr)) return;
      var v = get(lang, map[attr]);
      if (v) root.setAttribute(attr, v);
    });
    Array.prototype.forEach.call(root.querySelectorAll("[data-gp-t]"), function (el) {
      var v = get(lang, el.getAttribute("data-gp-t"), vars);
      if (v) el.textContent = v;
    });
    Array.prototype.forEach.call(root.querySelectorAll("[data-gp-aria]"), function (el) {
      var v = get(lang, el.getAttribute("data-gp-aria"));
      if (v) el.setAttribute("aria-label", v);
    });
    var nav = root.getAttribute("data-gp-aria-key");
    if (nav) { var n = get(lang, nav); if (n) root.setAttribute("aria-label", n); }
  }

  function applyAll() {
    Array.prototype.forEach.call(document.querySelectorAll("[data-gp-lang]"), apply);
  }

  window.GiftpinI18n = { apply: apply, get: get };
  applyAll();
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", applyAll);
})();
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(root, "assets", "giftpin-i18n.js"), buildThemeI18n());
  console.log("wrote giftpin-i18n.js");
}
