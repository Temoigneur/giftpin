/**
 * Pulls extractProductMetadata() out of the Chrome extension's popup.js, so
 * the phone app reads product pages with exactly the same code.
 *
 * Used by sync-extractor.mjs (writes src/extract.generated.ts) and by the
 * drift test in scripts/__tests__/mobile-extractor.test.ts at the repo root,
 * which fails if the two copies ever differ (CLAUDE.md hard rule #4).
 */
import { readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const POPUP_JS = resolve(here, "../../browser-extension/popup.js");
export const GENERATED_TS = resolve(here, "../src/extract.generated.ts");

/** The full source text of `function extractProductMetadata() { ... }`. */
export function extractorSource(popupJs = readFileSync(POPUP_JS, "utf8")) {
  const start = popupJs.indexOf("function extractProductMetadata()");
  if (start === -1) throw new Error("extractProductMetadata() not found in popup.js");

  // Walk braces to the function's closing one, skipping strings, regex
  // literals and comments well enough for this one hand-written function.
  let depth = 0;
  let i = popupJs.indexOf("{", start);
  for (; i < popupJs.length; i++) {
    const ch = popupJs[i];
    if (ch === "/" && popupJs[i + 1] === "/") {
      i = popupJs.indexOf("\n", i);
      continue;
    }
    if (ch === "/" && popupJs[i + 1] === "*") {
      i = popupJs.indexOf("*/", i) + 1;
      continue;
    }
    if (ch === '"' || ch === "'") {
      for (i++; popupJs[i] !== ch; i++) if (popupJs[i] === "\\") i++;
      continue;
    }
    if (ch === "/" && /[(,=:!&|?;]\s*$/.test(popupJs.slice(Math.max(0, i - 20), i))) {
      // regex literal
      for (i++; popupJs[i] !== "/"; i++) {
        if (popupJs[i] === "\\") i++;
        else if (popupJs[i] === "[") while (popupJs[++i] !== "]") if (popupJs[i] === "\\") i++;
      }
      continue;
    }
    if (ch === "{") depth++;
    if (ch === "}" && --depth === 0) break;
  }
  if (depth !== 0) throw new Error("Couldn't find the end of extractProductMetadata()");
  return popupJs.slice(start, i + 1);
}

export function generatedModule(source = extractorSource()) {
  return `// GENERATED by scripts/sync-extractor.mjs from browser-extension/popup.js.
// Do not edit: change popup.js, then run \`npm run sync-extractor\` here.
// A test at the repo root fails if this file drifts from popup.js.

export const EXTRACT_PRODUCT_METADATA_SOURCE = ${JSON.stringify(source)};
`;
}
